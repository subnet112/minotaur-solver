def pool_for(chain_id: int, tin: str, tout: str) -> str | None:
    a, b = sorted((tin.lower(), tout.lower()))
    return _BAL_POOLS.get((chain_id, a, b))


def quote(eth_call, chain_id: int, tin: str, tout: str, amount: int) -> int:
    """Exact Balancer output for tin->tout, or 0 if no pool / call fails.

    eth_call(to_addr, data_hex) -> hex string result (an eth_call thunk).
    """
    pid = pool_for(chain_id, tin, tout)
    if not pid or amount <= 0:
        return 0
    swaps = [(bytes.fromhex(pid[2:]), 0, 1, int(amount), b"")]
    assets = [Web3.to_checksum_address(tin), Web3.to_checksum_address(tout)]
    funds = (_ZERO, False, _ZERO, False)
    data = _QBS_SEL + _abi_encode(
        ["uint8", "(bytes32,uint256,uint256,uint256,bytes)[]", "address[]", "(address,bool,address,bool)"],
        [0, swaps, assets, funds],
    )
    try:
        r = eth_call(VAULT, "0x" + data.hex())
        if not r:
            return 0
        if isinstance(r, str):
            rb = bytes.fromhex(r[2:] if r.startswith("0x") else r)
        else:
            rb = bytes(r)
        deltas = _abi_decode(["int256[]"], rb)[0]
        out = -int(deltas[1])
        return out if out > 0 else 0
    except Exception:
        return 0


def build_calldata(tin: str, tout: str, amount: int, min_out: int, recipient: str,
                   chain_id: int, deadline: int) -> tuple[str, str] | None:
    """Return (approve_calldata, swap_calldata) hex for a tin->tout Balancer swap,
    or None if no pool. approve is on `tin` (spender=VAULT); swap is on VAULT."""
    pid = pool_for(chain_id, tin, tout)
    if not pid:
        return None
    tin_cs = Web3.to_checksum_address(tin)
    tout_cs = Web3.to_checksum_address(tout)
    rec = Web3.to_checksum_address(recipient)
    single = (bytes.fromhex(pid[2:]), 0, tin_cs, tout_cs, int(amount), b"")
    funds = (rec, False, rec, False)
    swap = _SWAP_SEL + _abi_encode(
        ["(bytes32,uint8,address,address,uint256,bytes)", "(address,bool,address,bool)", "uint256", "uint256"],
        [single, funds, int(min_out), int(deadline)],
    )
    approve = _APPROVE_SEL + _abi_encode(["address", "uint256"], [VAULT, int(amount)])
    return "0x" + approve.hex(), "0x" + swap.hex()
